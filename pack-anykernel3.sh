#!/usr/bin/env bash
# Packages a built begonia kernel into an AnyKernel3 flashable zip.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AK3="${AK3:-$here/anykernel3}"
OUTDIR="${OUTDIR:-$here/out}"
BRANCH="${BRANCH:-7.1}"
PANEL="${PANEL:-auto}"
KTITLE="${KTITLE:-mt6785-begonia}"

die() { printf 'error: %s\n' "$*" >&2; exit 1; }
info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  ok\033[0m %s\n' "$*"; }

[ $# -gt 0 ] && BRANCH="$1"
[ $# -gt 1 ] && PANEL="$2"

case "$PANEL" in auto|csot|tianma) ;; *) die "panel must be auto, csot or tianma" ;; esac

src="$OUTDIR/$BRANCH"
img="$src/Image"
zip_out="$OUTDIR/$KTITLE-$BRANCH-AnyKernel3.zip"

# 7.1 ships one DTB per panel; 6.16 ships a single un-suffixed begonia DTB
resolve_dtb() {
  local p
  if [ "$PANEL" != "auto" ]; then
    [ -s "$src/mt6785-xiaomi-begonia-$PANEL.dtb" ] || return 1
    printf '%s\n' "$src/mt6785-xiaomi-begonia-$PANEL.dtb"
    return 0
  fi
  for p in "$src"/mt6785-xiaomi-begonia-*.dtb; do
    [ -s "$p" ] || continue
    printf '%s\n' "$p"; return 0
  done
  [ -s "$src/mt6785-xiaomi-begonia.dtb" ] || return 1
  printf '%s\n' "$src/mt6785-xiaomi-begonia.dtb"
}

dtb="$(resolve_dtb)" || die "no begonia DTB in $src (looked for mt6785-xiaomi-begonia*.dtb)"
PANEL="$(basename "$dtb" .dtb)"

[ -d "$AK3" ] || die "missing AnyKernel3 assets: $AK3 (expected META-INF/ and tools/)"
[ -f "$AK3/META-INF/com/google/android/update-binary" ] || die "missing update-binary in $AK3"
[ -f "$AK3/tools/ak3-core.sh" ] || die "missing tools/ak3-core.sh in $AK3"
[ -s "$img" ] || die "no kernel Image at $img (build first)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cp -r "$AK3/META-INF" "$work/"
cp -r "$AK3/tools"     "$work/"
cp "$dtb"              "$work/"

# arm64 Image with the DTB appended, under the name AnyKernel3 prefers over plain Image
cat "$img" "$dtb" > "$work/Image-dtb"
ok "Image-dtb  ($(wc -c < "$work/Image-dtb") bytes)"

cat > "$work/anykernel.sh" <<AKSCRIPT
### AnyKernel3 Ramdisk Mod Script
## generated by pack-anykernel3.sh
### kernel.string=MT6785 mainline $BRANCH for Xiaomi begonia ($PANEL panel)

kernel.string=MT6785-mainline-$BRANCH-begonia-$PANEL
do.devicecheck=0
do.modules=0
do.systemless=1
do.cleanup=1
do.cleanuponabort=0

# begonia is an A-only device
BLOCK=/dev/block/bootdevice/by-name/boot;
IS_SLOT_DEVICE=0;
RAMDISK_COMPRESSION=auto;
PATCH_VBMETA_FLAG=auto;

. tools/ak3-core.sh;

dump_boot;
write_boot;
AKSCRIPT

chmod +x "$work/META-INF/com/google/android/update-binary" "$work/tools/"* 2>/dev/null || true

rm -f "$zip_out"
( cd "$work" && zip -r9X "$zip_out" . -x '.*' >/dev/null )

ok "$(basename "$zip_out") ($(du -h "$zip_out" | cut -f1))"
info "$zip_out"
unzip -l "$zip_out" | sed 's/^/      /'